export function parseTTC(s) {
  if (typeof s === "number") return s;
  if (!s) return 0;
  const v = parseFloat(String(s).replace(/\s/g, "").replace(/€/g, "").replace(",", "."));
  return isNaN(v) ? 0 : v;
}

export function eur(x) {
  return new Intl.NumberFormat("fr-FR", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(x) + " €";
}

function rangeFor(amount) {
  for (const r of RANGES) if (amount >= r.low && amount < r.high) return r;
  return RANGES[RANGES.length - 1];
}

function pay(amount, scheme) {
  const c = COEFFS[scheme];
  return c == null ? null : (amount * c) / 100;
}

// Montant a financer = total HT du devis (ligne « Total » du bloc PRODUITS : produits + livraison
// & installation + DEEE, avant TVA). A defaut, TTC / 1,2 (approximation : la TVA du devis n'est pas
// toujours exactement 20 % du total).
export function montantFinance(d) {
  const ht = Number(d?.total_ht) || 0;
  if (ht > 0) return Math.round(ht * 100) / 100;
  const ttc = Number(d?.total_ttc) || 0;
  return Math.round((ttc / 1.2) * 100) / 100;
}

// Renvoie un objet structure { montant, creditBail: [...lignes], location: [...lignes], premiers: {10,20,30} }
// Chaque ligne : { dureeSans, sans, duree, p10, p20, p30 }
export function computeFinancement(ht) {
  const r = rangeFor(ht);
  const build = (family) => {
    const off = family === "loc" ? LOC_OFFSET : 0;
    const rows = [];
    for (let i = 0; i < 4; i++) {
      rows.push({
        dureeSans: DUR_NO[i],
        sans: pay(ht, r.base[0] + i + off),
        duree: DUR_YES[i],
        p10: pay(ht, r.base[10] + i + off),
        p20: pay(ht, r.base[20] + i + off),
        p30: pay(ht, r.base[30] + i + off),
      });
    }
    return rows;
  };
  return {
    montant: ht,
    creditBail: build("cb"),
    location: build("loc"),
    premiers: { 10: ht * 0.1, 20: ht * 0.2, 30: ht * 0.3 },
    tranche: `${r.low.toLocaleString("fr-FR")}–${(r.high - 1).toLocaleString("fr-FR")} €`,
  };
}
